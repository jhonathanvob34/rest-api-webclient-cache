package com.example.webclient.model;

import java.time.LocalDateTime;
import java.util.UUID;

// ─────────────────────────────────────────────────────────────────────────────
// ProductResponse — the shape of the response OUR API sends back to the caller.
//
// The server generates id and createdAt — the client never sends them.
// Keeping Request and Response as separate records is good practice:
//   - The client cannot forge the id or timestamp
//   - The response shape can evolve independently of the request contract
//
// The factory method pattern (from()) is the same pattern used in v8's OrderEvent.create().
// ─────────────────────────────────────────────────────────────────────────────
public record ProductResponse(
        String id,
        String name,
        String category,
        Double price,
        Integer stock,
        String createdAt
) {
    // Factory method — called by the controller to build the response.
    // id and createdAt are generated by the server, same as OrderEvent.create() in v8.
    public static ProductResponse from(ProductRequest request) {
        return new ProductResponse(
                UUID.randomUUID().toString(),
                request.name(),
                request.category(),
                request.price(),
                request.stock(),
                LocalDateTime.now().toString()
        );
    }
}
